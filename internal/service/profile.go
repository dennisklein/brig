package service

import (
	"fmt"
	"strconv"

	"go.yaml.in/yaml/v3"

	"github.com/dennisklein/brig/internal/ocsync"
)

// SandboxHost is the name under which a sandbox reaches a service. OpenShell
// maps it to the gateway VM's own loopback interface, where brig runs a relay
// to the service's port on the host (see RelayUnit), so the name and the URL
// stay the same when the host changes networks.
const SandboxHost = "host.openshell.internal"

// URL is where a sandbox reaches the service.
func (s *Service) URL() string {
	return "http://" + SandboxHost + ":" + strconv.Itoa(s.Port)
}

// ProfileID is the ID of the OpenShell provider profile that brig generates
// for the service in each workspace that has a sandbox attached to it.
func ProfileID(service string) string { return ocsync.ReservedPrefix + service }

// ProviderName is the name of the OpenShell provider that holds the token of
// the sandbox's attachment. Names of services and sandboxes may both contain
// dashes, so two attachments may want the same name; brig then refuses the
// second one, as the provider exists already.
func ProviderName(service, sandbox string) string {
	return ocsync.ReservedPrefix + service + "-" + sandbox
}

// RelayUnit is the transient user unit in a gateway VM that relays the
// loopback port of the service to the service's port on the host. Its
// socket unit has the same name with .socket.
func RelayUnit(service string) string { return ocsync.ReservedPrefix + service }

// profile is an OpenShell provider profile, as brig writes it.
type profile struct {
	ID          string              `yaml:"id"`
	DisplayName string              `yaml:"display_name"`
	Description string              `yaml:"description"`
	Category    string              `yaml:"category"`
	Credentials []profileCredential `yaml:"credentials"`
	Discovery   profileDiscovery    `yaml:"discovery"`
	Endpoints   []profileEndpoint   `yaml:"endpoints"`
	Binaries    []string            `yaml:"binaries"`
}

type profileCredential struct {
	Name        string   `yaml:"name"`
	Description string   `yaml:"description"`
	EnvVars     []string `yaml:"env_vars"`
	Required    bool     `yaml:"required"`
	AuthStyle   string   `yaml:"auth_style"`
	HeaderName  string   `yaml:"header_name"`
}

type profileDiscovery struct {
	Credentials []string `yaml:"credentials"`
}

type profileEndpoint struct {
	Host        string `yaml:"host"`
	Port        int    `yaml:"port"`
	Protocol    string `yaml:"protocol"`
	Access      string `yaml:"access"`
	Enforcement string `yaml:"enforcement"`
}

// Profile returns the OpenShell provider profile of the service, of type t:
// its token, in the type's environment variables, may go only to the
// service's port at SandboxHost, and only from the programs that may call
// it.
func Profile(svc *Service, t Type) ([]byte, error) {
	auth, header := t.Credential.Auth, t.Credential.Header
	if auth == "" {
		auth = AuthBearer
	}
	if header == "" {
		header = "authorization"
	}
	p := profile{
		ID:          ProfileID(svc.Name),
		DisplayName: "brig service " + svc.Name,
		Description: fmt.Sprintf("The token of a sandbox for brig service %s (type %s). Generated by brig; brig service detach removes it.", svc.Name, svc.Type),
		Category:    "other",
		Credentials: []profileCredential{{
			Name:        "token",
			Description: "the sandbox's token for brig service " + svc.Name,
			EnvVars:     t.CredentialEnv(svc.Name),
			Required:    true,
			AuthStyle:   auth,
			HeaderName:  header,
		}},
		Discovery: profileDiscovery{Credentials: []string{"token"}},
		Endpoints: []profileEndpoint{{
			Host: SandboxHost, Port: svc.Port, Protocol: t.Protocol,
			Access: "read-write", Enforcement: "enforce",
		}},
		Binaries: svc.CallerBinaries(t),
	}
	return yaml.Marshal(&p)
}

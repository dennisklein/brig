package main

import (
	"errors"
	"fmt"
	"os"
	"path/filepath"
	"sort"
	"strings"
)

// modulePath is the path of brig's Go module.
const modulePath = "github.com/dennisklein/brig"

// findRepo returns the root of brig's source tree, looking from dir upwards
// for the go.mod of brig's module.
func findRepo(dir string) (string, error) {
	dir, err := filepath.Abs(dir)
	if err != nil {
		return "", err
	}
	for d := dir; ; d = filepath.Dir(d) {
		data, err := os.ReadFile(filepath.Join(d, "go.mod"))
		if err == nil && strings.Contains(string(data), "module "+modulePath+"\n") {
			return d, nil
		}
		if d == filepath.Dir(d) {
			return "", fmt.Errorf("%s is not in brig's source tree", dir)
		}
	}
}

// files is a set of generated files: contents by path relative to the root
// of the source tree, with forward slashes.
type files map[string]string

// paths returns the paths in sorted order.
func (f files) paths() []string {
	out := make([]string, 0, len(f))
	for p := range f {
		out = append(out, p)
	}
	sort.Strings(out)
	return out
}

// generatedMark starts every generated Markdown file; refreshing the
// reference deletes files that carry it and are no longer generated.
const generatedMark = "<!-- Generated by go generate ./...; do not edit. -->\n"

// write makes the files under root, and removes the stale ones that earlier
// runs made: those of dir that carry generatedMark, and all of cliDir.
func (f files) write(root string) error {
	for _, p := range f.paths() {
		full := filepath.Join(root, filepath.FromSlash(p))
		if err := os.MkdirAll(filepath.Dir(full), 0o755); err != nil { //nolint:gosec // G301: documentation is for everyone to read
			return err
		}
		if err := os.WriteFile(full, []byte(f[p]), 0o644); err != nil { //nolint:gosec // G306: documentation is for everyone to read
			return err
		}
	}
	stale, err := f.stale(root)
	if err != nil {
		return err
	}
	for _, p := range stale {
		if err := os.Remove(filepath.Join(root, filepath.FromSlash(p))); err != nil {
			return err
		}
	}
	return nil
}

// stale lists the generated files under root that f no longer has.
func (f files) stale(root string) ([]string, error) {
	var candidates []string
	err := filepath.WalkDir(filepath.Join(root, referenceDir), func(full string, d os.DirEntry, err error) error {
		if err != nil {
			if errors.Is(err, os.ErrNotExist) {
				return nil
			}
			return err
		}
		if d.IsDir() || !strings.HasSuffix(full, ".md") {
			return nil
		}
		rel, err := filepath.Rel(root, full)
		if err != nil {
			return err
		}
		if _, ok := f[filepath.ToSlash(rel)]; !ok {
			candidates = append(candidates, filepath.ToSlash(rel))
		}
		return nil
	})
	if err != nil {
		return nil, err
	}
	var out []string
	for _, rel := range candidates {
		data, err := os.ReadFile(filepath.Join(root, filepath.FromSlash(rel)))
		if err != nil {
			return nil, err
		}
		if strings.HasPrefix(string(data), generatedMark) {
			out = append(out, rel)
		}
	}
	return out, nil
}
